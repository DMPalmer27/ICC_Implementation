"""
File: inference_tables.py
Author: Daniel Palmer (d.m.palmer@wustl.edu)
Description: LaTeX tables and number macros for the inference paper, from
    results/inference_{S,F,C,R}.csv, so every number in paper/ is regenerated from the raw
    output instead of being typed in. Writes

        paper/generated/numbers.tex     \\newcommand macros used in the text
        paper/generated/tab_cost.tex    experiment C: cost vs stored size, d = 1 vs d = 2
        paper/generated/tab_real.tex    experiment R: real data at selected formats
        paper/generated/tab_sources.tex experiment S: per-source summary

Usage:
    .venv/bin/python tools/inference_tables.py [--suffix _fast]
"""

import _path  # noqa: F401

import argparse
import math
from pathlib import Path

import numpy as np

from plot_sweep import load

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
FAMILY_ORDER = ("gauss", "uniform", "bimodal", "discrete3", "laplace", "student3",
                "spiked", "exponential", "lognormal")


def truthy(v) -> bool:
    return v in (True, 1, "True", "true", "1")


def sci(v: float, digits: int = 1) -> str:
    """:return: v as LaTeX scientific notation, e.g. 3.1\\times10^{-3}"""
    if v == 0 or v is None or (isinstance(v, float) and math.isnan(v)):
        return "0"
    e = math.floor(math.log10(abs(v)))
    m = v / 10 ** e
    if e in (-1, 0, 1, 2):
        return f"{v:.{max(0, digits + 1 - e)}f}" if e < 2 else f"{v:.0f}"
    return f"{m:.{digits}f}\\times10^{{{e}}}"


def big(v: int) -> str:
    """:return: integer with LaTeX thin-space thousands separators"""
    return f"{int(v):,}".replace(",", "{,}")


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def source_label(r) -> str:
    rho = r.get("rho")
    if rho not in (None, 0, 0.0) and not (isinstance(rho, float) and math.isnan(rho)):
        return f"{r['family']} ($\\rho={rho:g}$)"
    return r["family"]


def numbers(S, F, C, R) -> list:
    allr = S + F + C + R
    out = [f"% generated by tools/inference_tables.py -- do not edit"]
    out.append(macro("NRuns", big(len(allr))))
    out.append(macro("NScores", big(sum(r["queries"] for r in allr))))
    out.append(macro("NExactRuns", big(sum(truthy(r["all_exact"]) for r in allr))))
    out.append(macro("NViolations", big(sum(r["bound_violations"] or 0 for r in allr))))
    out.append(macro("NSRuns", big(len(S))))
    out.append(macro("NFRuns", big(len(F))))
    out.append(macro("NRRuns", big(len(R))))
    if S:
        ratio = max(r["err_max"] / r["bound_max"] for r in S)
        out.append(macro("SMaxErrOverBound", f"{ratio:.2f}"))
        clean = [r for r in S if (r["clipped_values"] or 0) == 0]
        if clean:
            out.append(macro("SMaxErrClean", sci(max(r["err_max"] for r in clean))))
            out.append(macro("SMaxErrOverBoundClean",
                             f"{max(r['err_max'] / r['bound_max'] for r in clean):.2f}"))
            out.append(macro("SMeanErrOverBoundClean",
                             f"{np.mean([r['err_mean'] / r['bound_mean'] for r in clean]):.2f}"))
        clip = [r for r in S if (r["clipped_values"] or 0) > 0]
        out.append(macro("SNClippedRuns", big(len(clip))))
        out.append(macro("SMaxErrClipped", sci(max([r["err_max"] for r in clip] or [0]))))
        for task, met, name in (("linear", "r2", "Lin"), ("logistic", "acc", "Log"),
                                ("softmax", "acc", "Soft")):
            rows = [r for r in S if r["task"] == task]
            if rows:
                gap = max(abs(r[f"scheme_{met}"] - r[f"float_{met}"]) for r in rows)
                out.append(macro(f"SMaxGap{name}", sci(gap)))
                rc = [r for r in rows if (r["clipped_values"] or 0) == 0]
                if rc:
                    gc = max(abs(r[f"scheme_{met}"] - r[f"float_{met}"]) for r in rc)
                    out.append(macro(f"SMaxGap{name}Clean", sci(gc)))
                    out.append(macro(f"SNClean{name}", big(len(rc))))
                if task != "linear":
                    out.append(macro(f"SFlips{name}", big(sum(r["flips"] for r in rows))))
                    out.append(macro(f"SDecisions{name}", big(sum(r["N"] for r in rows))))
        dec = [r for r in S if r["task"] != "linear"]
        out.append(macro("SFlipsOutsideBound", big(sum(max(0, r["flips"] - r["flip_possible"])
                                                       for r in dec))))
        out.append(macro("SMaxErrUnclippedRows", sci(max(r["err_max_unclipped"] for r in S
                                                         if r["err_max_unclipped"] is not None))))
        low = ("spiked", "discrete3")
        mn = [r["m"] / r["n"] for r in S if r["family"] not in low]
        out.append(macro("SMoverNMin", f"{min(mn):.2f}"))
        out.append(macro("SMoverNMax", f"{max(mn):.2f}"))
        h = [r["h"] for r in S if r["family"] not in low]
        out.append(macro("SHMin", f"{min(h):.2f}"))
        out.append(macro("SHMax", f"{max(h):.2f}"))
        sp = [r for r in S if r["family"] == "spiked"]
        if sp:
            out.append(macro("SSpikedH", f"{np.mean([r['h'] for r in sp]):.2f}"))
            out.append(macro("SSpikedMoverN", f"{np.mean([r['m'] / r['n'] for r in sp]):.2f}"))
        d3 = [r for r in S if r["family"] == "discrete3"]
        if d3:
            out.append(macro("SDiscH", f"{np.mean([r['h'] for r in d3]):.2f}"))
            out.append(macro("SDiscMoverN", f"{np.mean([r['m'] / r['n'] for r in d3]):.2f}"))
        out.append(macro("SLogQMin", f"{min(r['log2_q'] for r in S):.1f}"))
        out.append(macro("SLogQMax", f"{max(r['log2_q'] for r in S):.1f}"))
    if allr:
        out.append(macro("EpsCMin", sci(min(r["eps_c"] for r in allr))))
        out.append(macro("EpsCMax", sci(max(r["eps_c"] for r in allr))))
        out.append(macro("EpsCAltMax", sci(max(r["eps_c_alt"] for r in allr))))
        out.append(macro("EpsCBitsMax", sci(max(r["eps_c_bits"] for r in allr))))
    if C:
        last = max(C, key=lambda r: r["n"])
        out.append(macro("CN", big(last["N"])))
        out.append(macro("Cn", big(last["n"])))
        out.append(macro("CLam", big(last["lam"])))
        if last.get("d2_lam"):
            out.append(macro("CDTwoLam", big(last["d2_lam"])))
            out.append(macro("CRatio", big(round(last["d2_lam"] / last["lam"]))))
        tot = sum(last[k] for k in ("t_encode", "t_store", "t_build", "t_evaluate", "t_decode"))
        out.append(macro("CTotal", f"{tot:.0f}"))
        out.append(macro("CPerScore", sci(1000 * (last["t_evaluate"] + last["t_decode"])
                                          / last["queries"])))
    for name, met in (("diabetes", "r2"), ("wine", "acc")):
        rows = [r for r in R if r["family"] == name and r["f_X"] == 8 and r["f_w"] == 8
                and float(r["clip_X"]) == 4.0]
        if rows:
            r = rows[0]
            tag = "Diab" if name == "diabetes" else "Wine"
            out.append(macro(f"R{tag}Float", f"{r[f'float_{met}']:.4f}"))
            out.append(macro(f"R{tag}Scheme", f"{r[f'scheme_{met}']:.4f}"))
            out.append(macro(f"R{tag}M", big(r["m"])))
            out.append(macro(f"R{tag}Lam", big(r["lam"])))
            out.append(macro(f"R{tag}n", big(r["n"])))
            out.append(macro(f"R{tag}H", f"{r['h']:.3f}"))
            out.append(macro(f"R{tag}LogQ", f"{r['log2_q']:.1f}"))
            out.append(macro(f"R{tag}Clipped", big(r["clipped_values"])))
            out.append(macro(f"R{tag}Flips", big(r["flips"])))
            out.append(macro(f"R{tag}ErrMax", sci(r["err_max"], 2)))
            out.append(macro(f"R{tag}Wall", f"{r['wall']:.0f}"))
    return out


def tab_cost(C) -> str:
    C = sorted(C, key=lambda r: r["n"])
    lines = [r"\begin{tabular}{rrrrrrrrr}", r"\toprule",
             r"$N$ & $n$ & $\log_2 q$ & $m$ & $\lambda$ & store & eval & decode & $\lambda$ at $d{=}2$ \\",
             r"& & & & & (s) & (s) & (s) & (plan) \\", r"\midrule"]
    for r in C:
        d2 = big(r["d2_lam"]) if r.get("d2_lam") else "--"
        lines.append(f"{r['N']} & {big(r['n'])} & {r['log2_q']:.1f} & {big(r['m'])} & "
                     f"{big(r['lam'])} & {r['t_store']:.2f} & {r['t_evaluate']:.2f} & "
                     f"{r['t_decode']:.2f} & {d2} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def tab_real(R) -> str:
    lines = [r"\begin{tabular}{llrrrrrrl}", r"\toprule",
             r"data & $f_X/f_w$, clip & $\log_2 q$ & $h$ & $m$ & clipped & max err & flips & metric (float $\to$ scheme) \\",
             r"\midrule"]
    keep = [(f, w, c) for f, w, c in [(4, 4, 4.0), (6, 6, 4.0), (8, 8, 4.0), (8, 8, 8.0)]]
    for name, met, lab in (("diabetes", "r2", "$R^2$"), ("wine", "acc", "acc.")):
        for (fx, fw, clip) in keep:
            rows = [r for r in R if r["family"] == name and r["f_X"] == fx and r["f_w"] == fw
                    and float(r["clip_X"]) == clip]
            if not rows:
                continue
            r = rows[0]
            flips = "--" if name == "diabetes" else str(r["flips"])
            lines.append(f"{name} & {fx}/{fw}, $\\pm{clip:g}\\sigma$ & {r['log2_q']:.1f} & "
                         f"{r['h']:.3f} & {big(r['m'])} & {r['clipped_values']} & "
                         f"{r['err_max']:.3f} & {flips} & {lab} {r[f'float_{met}']:.4f} $\\to$ "
                         f"{r[f'scheme_{met}']:.4f} \\\\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    return "\n".join(lines)


def tab_sources(S) -> str:
    labels = sorted({source_label(r) for r in S},
                    key=lambda s: (FAMILY_ORDER.index(s.split(" ")[0])
                                   if s.split(" ")[0] in FAMILY_ORDER else 99, s))
    lines = [r"\begin{tabular}{lrrrrrr}", r"\toprule",
             r"source & $h$ & $m/n$ & clipped & max err & $\max|\Delta R^2|$ & flips \\",
             r"\midrule"]
    for lab in labels:
        rows = [r for r in S if source_label(r) == lab]
        lin = [r for r in rows if r["task"] == "linear"]
        dec = [r for r in rows if r["task"] != "linear"]
        gap = max([abs(r["scheme_r2"] - r["float_r2"]) for r in lin] or [float("nan")])
        lines.append(f"{lab} & {np.mean([r['h'] for r in rows]):.2f} & "
                     f"{np.mean([r['m'] / r['n'] for r in rows]):.2f} & "
                     f"{sum(r['clipped_values'] for r in rows)} & "
                     f"{max(r['err_max'] for r in rows):.3f} & ${sci(gap)}$ & "
                     f"{sum(r['flips'] for r in dec)}/{sum(r['N'] for r in dec)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--suffix", default="")
    args = ap.parse_args()
    S, F, C, R = (load(RESULTS / f"inference_{e}{args.suffix}.csv") for e in "SFCR")
    out = ROOT / "paper" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    (out / "numbers.tex").write_text("\n".join(numbers(S, F, C, R)) + "\n")
    if C:
        (out / "tab_cost.tex").write_text(tab_cost(C) + "\n")
    if R:
        (out / "tab_real.tex").write_text(tab_real(R) + "\n")
    if S:
        (out / "tab_sources.tex").write_text(tab_sources(S) + "\n")
    print(f"  wrote {', '.join(p.name for p in sorted(out.iterdir()))} -> {out}")


if __name__ == "__main__":
    main()
